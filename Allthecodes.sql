CREATE TABLE audit_log (
    log_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    log_timestamp   TIMESTAMP DEFAULT SYSTIMESTAMP,
    process_name    VARCHAR2(50) NOT NULL,
    product_id      NUMBER(6),
    log_message     VARCHAR2(500)
);


SELECT
    product_id,
    product_name,
    unit_cost,
    reorder_point
FROM
    products
ORDER BY
    product_id;


SELECT
    s.stock_id,
    s.warehouse_id,
    p.product_name,
    s.stock_level
FROM
    inventory_stock s
JOIN
    products p ON s.product_id = p.product_id
ORDER BY
    s.product_id;
