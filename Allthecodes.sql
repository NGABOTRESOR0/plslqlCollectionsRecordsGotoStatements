CREATE TABLE inventory_stock (
    stock_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    product_id      NUMBER(6) NOT NULL,
    warehouse_id    NUMBER(2) NOT NULL,
    stock_level     NUMBER(5) NOT NULL,
    last_checked    DATE DEFAULT SYSDATE,
    CONSTRAINT fk_product_stock FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT chk_stock_level CHECK (stock_level >= 0)
);

